# build-source.sh — Localhost Hardware-Optimized Source Builder (-march=native)
# ==============================================================================
# Usage:
#   sf build status                 Show detected localhost CPU & build flags
#   sf build profile                Generate ~/.config/superfedora/hardware-flags.env
#   sf build all [--force]          Compile workstation suite for localhost CPU
#   sf build <component> [--force]  Compile one target (wlctl|bluetui|wiremix|tuigreet|fuzzel|btop)
# ==============================================================================
set -euo pipefail

SF_ROOT="$(cd "$(dirname "$(realpath "${BASH_SOURCE[0]}")")/.." && pwd)"
export SF_ROOT
STATE_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/superfedora"
STAMP_DIR="$STATE_DIR/source-built"
HW_ENV="$STATE_DIR/hardware-flags.env"
export PATH="$HOME/.local/bin:$HOME/.cargo/bin:/usr/bin:/bin:$PATH"

detect_host_hw() {
    CPU_ARCH="$(uname -m)"
    CPU_MODEL="$(awk -F': ' '/^model name/{print $2; exit}' /proc/cpuinfo 2>/dev/null || lscpu 2>/dev/null | awk -F': +' '/Model name/{print $2; exit}' || echo "$CPU_ARCH")"
    CPU_JOBS="$(nproc 2>/dev/null || echo 4)"
    MARCH_TARGET=""
    if command -v rustc >/dev/null 2>&1; then
        MARCH_TARGET="$(rustc --print target-cpus 2>/dev/null | sed -n 's/.*currently \([^)]*\)).*/\1/p' | head -1)"
    fi
    if [[ -z "$MARCH_TARGET" && -x /usr/bin/gcc ]]; then
        MARCH_TARGET="$(/usr/bin/gcc -march=native -Q --help=target 2>/dev/null | awk '/^\s*-march=/{print $2; exit}')"
    fi
    MARCH_TARGET="${MARCH_TARGET:-native}"
    ISA_FLAGS="$(grep -m1 '^flags' /proc/cpuinfo 2>/dev/null | grep -oE '\b(avx512f|avx2|avx|fma|bmi2|aes|vaes|sha_ni|sse4_2)\b' | sort -u | tr '\n' ' ' | sed 's/ $//' || echo "standard")"
    [[ -n "$ISA_FLAGS" ]] || ISA_FLAGS="standard"

    HOST_CFLAGS="-O3 -pipe -march=native -mtune=native -flto=auto -fno-plt"
    HOST_CXXFLAGS="-O3 -pipe -march=native -mtune=native -flto=auto -fno-plt"
    HOST_LDFLAGS="-Wl,-O1,--sort-common,--as-needed,-z,relro,-z,now -flto=auto"
    HOST_RUSTFLAGS="-C opt-level=3 -C target-cpu=native -C codegen-units=1 -C strip=symbols"
    HOST_MAKEFLAGS="-j${CPU_JOBS}"
}

write_hw_profile() {
    detect_host_hw
    mkdir -p "$STATE_DIR" "$STAMP_DIR" "$HOME/.local/bin"
    cat > "$HW_ENV" <<EOF
# Generated by SuperFedora Localhost Source Builder
SF_CPU_MODEL="$CPU_MODEL"
SF_CPU_ARCH="$CPU_ARCH"
SF_MARCH_TARGET="$MARCH_TARGET"
SF_CPU_JOBS="$CPU_JOBS"
SF_ISA_FLAGS="$ISA_FLAGS"
export CFLAGS="$HOST_CFLAGS"
export CXXFLAGS="$HOST_CXXFLAGS"
export LDFLAGS="$HOST_LDFLAGS"
export RUSTFLAGS="$HOST_RUSTFLAGS"
export MAKEFLAGS="$HOST_MAKEFLAGS"
export CARGO_BUILD_JOBS="$CPU_JOBS"
export CMAKE_BUILD_PARALLEL_LEVEL="$CPU_JOBS"
EOF
    echo "source" > "$STATE_DIR/build-mode"
    local rpmmacros="$HOME/.rpmmacros"
    if [[ ! -f "$rpmmacros" ]] || ! grep -q "SuperFedora localhost" "$rpmmacros" 2>/dev/null; then
        cat >> "$rpmmacros" <<EOF

# SuperFedora localhost hardware optimization profile ($MARCH_TARGET)
%_smp_mflags -j${CPU_JOBS}
%optflags ${HOST_CFLAGS}
EOF
    fi
}

is_source_built() {
    local comp="$1" bin="${2:-$1}"
    detect_host_hw
    command -v "$bin" >/dev/null 2>&1 &&
    [[ -f "$STAMP_DIR/$comp.stamp" ]] &&
    grep -q "^arch=$MARCH_TARGET$" "$STAMP_DIR/$comp.stamp" 2>/dev/null
}

mark_built() {
    local comp="$1"
    mkdir -p "$STAMP_DIR"
    printf 'component=%s\narch=%s\nbuilt_at=%s\ncflags=%s\nrustflags=%s\n' \
        "$comp" "$MARCH_TARGET" "$(date -u +%FT%TZ)" "$HOST_CFLAGS" "$HOST_RUSTFLAGS" > "$STAMP_DIR/$comp.stamp"
}

ensure_build_deps() {
    local -a pkgs=("$@") missing=()
    local p
    for p in "${pkgs[@]}"; do
        rpm -q --quiet "$p" 2>/dev/null || missing+=("$p")
    done
    if [[ ${#missing[@]} -gt 0 ]]; then
        if [[ $EUID -eq 0 ]]; then
            dnf install -y "${missing[@]}"
        else
            sudo dnf install -y "${missing[@]}"
        fi
    fi
}

cargo_native_install() {
    local comp="$1" crate="$2" bin="$3"
    shift 3
    if ! command -v cargo >/dev/null 2>&1; then
        curl -fsSL https://sh.rustup.rs | sh -s -- -y --no-modify-path
    fi
    local cc_bin="gcc" cxx_bin="g++"
    [[ -x /usr/bin/gcc ]] && cc_bin="/usr/bin/gcc"
    [[ -x /usr/bin/g++ ]] && cxx_bin="/usr/bin/g++"
    echo "[+] Compiling $comp from source for localhost ($MARCH_TARGET, $CPU_JOBS threads)..."
    CC="$cc_bin" CXX="$cxx_bin" CFLAGS="$HOST_CFLAGS" CXXFLAGS="$HOST_CXXFLAGS" LDFLAGS="$HOST_LDFLAGS" \
    RUSTFLAGS="$HOST_RUSTFLAGS" CARGO_BUILD_JOBS="$CPU_JOBS" \
        cargo install "$@" "$crate" --locked --force --root "$HOME/.local"
    [[ -x "$HOME/.local/bin/$bin" ]] && mark_built "$comp"
}

build_target() {
    local comp="$1" force="${2:-0}"
    detect_host_hw
    write_hw_profile
    if [[ "$force" -eq 0 ]] && is_source_built "$comp" "$comp"; then
        echo "[OK] $comp already compiled for localhost ($MARCH_TARGET)"
        return 0
    fi
    local cc_bin="gcc" cxx_bin="g++"
    [[ -x /usr/bin/gcc ]] && cc_bin="/usr/bin/gcc"
    [[ -x /usr/bin/g++ ]] && cxx_bin="/usr/bin/g++"
    case "$comp" in
        wlctl)
            ensure_build_deps gcc make pkgconf-pkg-config dbus-devel
            cargo_native_install wlctl https://github.com/aashish-thapa/wlctl wlctl --git ;;
        bluetui)
            ensure_build_deps gcc make pkgconf-pkg-config dbus-devel
            cargo_native_install bluetui bluetui bluetui ;;
        wiremix)
            ensure_build_deps gcc clang make pkgconf-pkg-config pipewire-devel alsa-lib-devel
            cargo_native_install wiremix wiremix wiremix ;;
        tuigreet)
            ensure_build_deps gcc make
            cargo_native_install tuigreet tuigreet tuigreet
            if [[ -x "$HOME/.local/bin/tuigreet" && -w /usr/bin ]]; then
                install -m 755 "$HOME/.local/bin/tuigreet" /usr/bin/tuigreet
            fi ;;
        fuzzel)
            ensure_build_deps gcc meson ninja-build pkgconf-pkg-config wayland-devel wayland-protocols-devel \
                libxkbcommon-devel pixman-devel cairo-devel pango-devel fcft-devel tllist-devel \
                fontconfig-devel libpng-devel librsvg2-devel scdoc
            local tmp; tmp="$(mktemp -d)"
            echo "[+] Compiling fuzzel from source for localhost ($MARCH_TARGET, $CPU_JOBS threads)..."
            git clone --depth 1 https://codeberg.org/dnkl/fuzzel.git "$tmp/fuzzel"
            CC="$cc_bin" CFLAGS="$HOST_CFLAGS" LDFLAGS="$HOST_LDFLAGS" \
                meson setup "$tmp/fuzzel/build" "$tmp/fuzzel" --prefix="$HOME/.local" -Dbuildtype=release -Db_lto=true
            ninja -C "$tmp/fuzzel/build" -j"$CPU_JOBS" install
            rm -rf "$tmp"
            [[ -x "$HOME/.local/bin/fuzzel" ]] && mark_built fuzzel ;;
        btop)
            ensure_build_deps gcc-c++ make
            local tmp; tmp="$(mktemp -d)"
            echo "[+] Compiling btop from source for localhost ($MARCH_TARGET, $CPU_JOBS threads)..."
            git clone --depth 1 https://github.com/aristocratos/btop.git "$tmp/btop"
            CXX="$cxx_bin" make -C "$tmp/btop" OPTFLAGS="-O3 -march=native -mtune=native -flto=auto" -j"$CPU_JOBS"
            make -C "$tmp/btop" PREFIX="$HOME/.local" install
            rm -rf "$tmp"
            [[ -x "$HOME/.local/bin/btop" ]] && mark_built btop ;;
        *)
            echo "error: unknown source target '$comp' (expected: wlctl, bluetui, wiremix, tuigreet, fuzzel, btop, all)" >&2
            exit 2 ;;
    esac
    echo "[OK] Built $comp for localhost CPU ($MARCH_TARGET)"
}

print_status() {
    detect_host_hw
    local mode="quick"
    [[ -f "$STATE_DIR/build-mode" ]] && mode="$(tr -d '[:space:]' < "$STATE_DIR/build-mode")"
    printf 'SuperFedora Localhost Hardware Build Profile\n'
    printf '  Install Mode   : %s\n' "$mode"
    printf '  CPU Model      : %s\n' "$CPU_MODEL"
    printf '  Target Arch    : -march=%s (%s, %s threads)\n' "$MARCH_TARGET" "$CPU_ARCH" "$CPU_JOBS"
    printf '  ISA Extensions : %s\n' "$ISA_FLAGS"
    printf '  CFLAGS         : %s\n' "$HOST_CFLAGS"
    printf '  RUSTFLAGS      : %s\n' "$HOST_RUSTFLAGS"
    printf '  Profile File   : %s (%s)\n\n' "$HW_ENV" "$([[ -f "$HW_ENV" ]] && echo present || echo not-generated)"
    printf '  COMPONENT   STATE           BINARY\n'
    printf '  ---------   -------------   ------\n'
    local c
    for c in wlctl bluetui wiremix tuigreet fuzzel btop; do
        local st="binary/pkg"
        is_source_built "$c" "$c" && st="source-native"
        printf '  %-10s  [%-13s] %s\n' "$c" "$st" "$(command -v "$c" 2>/dev/null || echo missing)"
    done
}

ACTION="status"
FORCE=0
ACTION_SET=0
for arg in "$@"; do
    case "$arg" in
        --force|-f) FORCE=1 ;;
        -h|--help|help) sed -n '7,11p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        --status|--check) ACTION="status"; ACTION_SET=1 ;;
        *)
            if [[ $ACTION_SET -eq 0 ]]; then
                ACTION="$arg"
                ACTION_SET=1
            fi ;;
    esac
done
[[ $ACTION_SET -eq 0 && $FORCE -eq 1 ]] && ACTION="all"

case "$ACTION" in
    status|--status|check|--check|list)
        print_status ;;
    profile|init)
        write_hw_profile
        echo "[OK] Localhost hardware profile written to $HW_ENV (-march=$MARCH_TARGET, $CPU_JOBS threads)" ;;
    all)
        write_hw_profile
        for t in wlctl bluetui wiremix tuigreet fuzzel btop; do
            build_target "$t" "$FORCE"
        done ;;
    wlctl|bluetui|wiremix|tuigreet|fuzzel|btop)
        build_target "$ACTION" "$FORCE" ;;
    *)
        if [[ -x "$SF_ROOT/lib/forge.sh" ]]; then
            exec "$SF_ROOT/lib/forge.sh" "$@"
        fi
        echo "unknown build command: $ACTION" >&2
        sed -n '7,11p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' >&2
        exit 2 ;;
esac
